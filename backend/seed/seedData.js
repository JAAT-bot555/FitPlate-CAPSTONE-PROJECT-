function createRecipe({
  name,
  cuisine,
  category,
  cookingTime,
  calories,
  protein,
  carbohydrates,
  fats,
  estimatedCost,
  dietaryTags,
  ingredients,
}) {
  return {
    name,
    cuisine,
    category,
    cookingTime,
    calories,
    protein,
    carbohydrates,
    fats,
    estimatedCost,
    dietaryTags,
    description: `${name} - a wholesome ${cuisine} ${category} dish.`,
    instructions: [
      'Wash, chop, and measure all required ingredients.',
      'Cook the base ingredients with spices and oil over medium heat until tender.',
      'Garnish and serve warm.',
    ],
    ingredients: ingredients.map(([ingName, quantity, unit]) => ({
      name: ingName,
      quantity,
      unit,
    })),
  };
}

